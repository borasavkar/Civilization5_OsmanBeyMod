def build_audio():
    os.makedirs(os.path.join(MOD1, "Sounds"), exist_ok=True)
    for target, src in MUSIC.items():
        shutil.copyfile(os.path.join(MUSIC_SRC, src), os.path.join(MOD1, "Sounds", target + ".mp3"))
    a = Doc()
    names = sorted(MUSIC)
    a.table("Audio_Sounds", [{"SoundID": "SND_" + n.upper(), "Filename": n, "LoadType": "DynamicResident"}
                             for n in names])
    scripts = []

    def script(sid, n):
        scripts.append({"ScriptID": sid, "SoundID": "SND_" + n.upper(), "SoundType": "GAME_MUSIC",
                        "MinVolume": MUSIC_VOLUME, "MaxVolume": MUSIC_VOLUME, "IsMusic": True})
    tag = SOUNDTRACK_TAG.upper()
    for i, n in enumerate(MUSIC_PEACE, 1):
        script("SONG_%s_PEACE_%d" % (tag, i), n)
    for i, n in enumerate(MUSIC_WAR, 1):
        script("SONG_%s_WAR_%d" % (tag, i), n)
    script("AS2D_LEADER_MUSIC_OB_OSMAN_PEACE", LEADER_PEACE)
    script("AS2D_LEADER_MUSIC_OB_OSMAN_WAR", LEADER_WAR)
    a.table("Audio_2DSounds", scripts)
    write(os.path.join(MOD1, "Core", "OB_Audio.xml"), a.render())


def copy_block(table, key, mapname):
    return ("CREATE TABLE OB_Tmp AS SELECT * FROM {t} WHERE 0;\n"
            "INSERT INTO OB_Tmp SELECT t.* FROM {t} t INNER JOIN {m} m ON t.{k} = m.BaseType;\n"
            "UPDATE OB_Tmp SET {k} = (SELECT NewType FROM {m} WHERE BaseType = OB_Tmp.{k});\n"
            "INSERT INTO {t} SELECT * FROM OB_Tmp;\n"
            "DROP TABLE OB_Tmp;\n").format(t=table, k=key, m=mapname)


