TR_MAP = str.maketrans({"ş": "s", "Ş": "S", "ğ": "g", "Ğ": "G", "ı": "i", "İ": "I"})


def tr_safe(s):
    """The Civ V font has no s-cedilla, soft g or dotless i; o-umlaut, u-umlaut and c-cedilla are fine."""
    return s.translate(TR_MAP)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\r\n") as fh:
        fh.write(text)


class Doc:
    def __init__(self):
        self.tables = []

    def table(self, name, rows):
        self.tables.append((name, rows))

    def render(self):
        out = ['<?xml version="1.0" encoding="utf-8"?>',
               "<!-- Generated by tools/build_mod.py. Do not edit by hand. -->",
               "<GameData>"]
        for name, rows in self.tables:
            out.append("\t<%s>" % name)
            for row in rows:
                out.append("\t\t<Row>")
                for k, v in row.items():
                    if v is None:
                        continue
                    if isinstance(v, bool):
                        v = "true" if v else "false"
                    out.append("\t\t\t<%s>%s</%s>" % (k, escape(str(v)), k))
                out.append("\t\t</Row>")
            out.append("\t</%s>" % name)
        out += ["</GameData>", ""]
        return "\n".join(out)


def text_xml(rows):
    out = ['<?xml version="1.0" encoding="utf-8"?>',
           "<!-- Generated by tools/build_mod.py. Do not edit by hand. -->",
           "<GameData>", "\t<Language_en_US>"]
    for tag in sorted(rows):
        out.append('\t\t<Row Tag="%s">\n\t\t\t<Text>%s</Text>\n\t\t</Row>' % (tag, escape(tr_safe(rows[tag]))))
    out += ["\t</Language_en_US>", "</GameData>", ""]
    return "\n".join(out)


